-- 1. Create the sequence for generating order IDs
CREATE SEQUENCE FOOD_ORDER_SEQ
START WITH 1
INCREMENT BY 1
NOCACHE
NOCYCLE;

-- 2. Create the food orders table
CREATE TABLE FOOD_ORDERS (
    ORDER_ID NUMBER(19) PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(255) NOT NULL,
    FOOD_ITEM VARCHAR2(255) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL,
    PRICE NUMBER(10,2) NOT NULL,
    CONSTRAINT CHK_FOOD_ORDER_QUANTITY CHECK (QUANTITY >= 1),
    CONSTRAINT CHK_FOOD_ORDER_PRICE CHECK (PRICE >= 0)
);

-- 3. Verify the table
SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME = 'FOOD_ORDERS';

-- 4. Verify the sequence
SELECT SEQUENCE_NAME
FROM USER_SEQUENCES
WHERE SEQUENCE_NAME = 'FOOD_ORDER_SEQ';

-- 5. Test the table
SELECT * FROM FOOD_ORDERS;

